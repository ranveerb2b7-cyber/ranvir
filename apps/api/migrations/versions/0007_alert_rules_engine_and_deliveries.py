DELIVERY_ORGS = """
CREATE FUNCTION alert_delivery_orgs(p_stale_after_s integer)
RETURNS TABLE (organization_id uuid)
LANGUAGE sql VOLATILE SECURITY DEFINER SET search_path = public, pg_temp AS $$
  WITH reset AS (
    UPDATE alert_deliveries
       SET status = 'pending', next_attempt_at = now(),
           last_error = 'The worker sending this stopped; retried.'
     WHERE status = 'sending'
       AND claimed_at < now() - make_interval(secs => p_stale_after_s)
    RETURNING organization_id
  )
  SELECT organization_id FROM reset
  UNION
  SELECT d.organization_id FROM alert_deliveries d
  WHERE d.status = 'pending' AND (d.next_attempt_at IS NULL OR d.next_attempt_at <= now())
$$
"""


